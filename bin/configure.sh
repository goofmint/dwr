#!/usr/bin/env bash
# Interactive setup wizard for Daily Work Capture System.
# Creates required directories and writes ~/.config/dwr/config.toml.
set -euo pipefail

if [ ! -t 0 ]; then
    echo "configure.sh: must be run interactively (TTY required)" >&2
    exit 1
fi

DWR_REPO="$(cd "$(dirname "$0")/.." && pwd)"
CONFIG_DIR="$HOME/.config/dwr"
CONFIG_FILE="$CONFIG_DIR/config.toml"
CAPTURE_DIR="${CAPTURE_DIR:-$HOME/capture}"
LIST_DEVICES="$DWR_REPO/bin/list-audio-devices.sh"

# ---- intro ----
cat <<EOF
=== Daily Work Capture System: setup wizard ===

This script will create:
  - $CAPTURE_DIR/{image,audio,text,state}/
  - $CONFIG_DIR/config.toml

EOF

read -rp "Continue? [Y/n] " confirm
case "$confirm" in
    [Nn]*) echo "Aborted."; exit 0 ;;
esac
echo

# ---- directories ----
echo "Creating directories..."
mkdir -p "$CONFIG_DIR"
mkdir -p \
    "$CAPTURE_DIR/image/incoming" "$CAPTURE_DIR/image/processed" \
    "$CAPTURE_DIR/audio/incoming" "$CAPTURE_DIR/audio/processed" \
    "$CAPTURE_DIR/text/image" "$CAPTURE_DIR/text/audio" \
    "$CAPTURE_DIR/state"
echo "  $CONFIG_DIR"
echo "  $CAPTURE_DIR"
echo

# ---- existing config check ----
if [ -f "$CONFIG_FILE" ]; then
    echo "Existing config detected: $CONFIG_FILE"
    read -rp "Overwrite? [y/N] " over
    case "$over" in
        [Yy]*) ;;
        *) echo "Keeping existing config. Done."; exit 0 ;;
    esac
    echo
fi

# ---- step 1: audio input device ----
echo "[1/3] Audio input device"
echo
echo "Available input devices (\"* \" = current system default):"

if [ ! -x "$LIST_DEVICES" ]; then
    echo "  (warning: $LIST_DEVICES not found; cannot enumerate devices)" >&2
    devices=()
else
    mapfile -t devices < <("$LIST_DEVICES")
fi

if [ "${#devices[@]}" -eq 0 ]; then
    echo "  (none detected)"
else
    for i in "${!devices[@]}"; do
        printf "  %2d. %s\n" "$((i+1))" "${devices[$i]}"
    done
fi
echo "   0. (no override — use system default)"
echo

read -rp "Select number [0]: " sel
sel="${sel:-0}"

audio_input_device=""
if [ "$sel" != "0" ]; then
    if [[ "$sel" =~ ^[1-9][0-9]*$ ]] && [ "$sel" -le "${#devices[@]}" ]; then
        line="${devices[$((sel-1))]}"
        # Strip "* " or "  " prefix and " (Nch)" suffix.
        audio_input_device="$(printf '%s' "$line" | sed -E 's/^[* ][[:space:]]*//; s/ \([0-9]+ch\)$//')"
    else
        echo "  Invalid selection. Falling back to system default." >&2
    fi
fi
echo

# ---- step 2: silence threshold ----
echo "[2/3] Silence threshold"
echo
echo "  Threshold (dB) for ffmpeg silence detection (segment start/stop)."
echo "  More negative = more sensitive."
echo "  Typical: -40dB (room ambient), -30dB (loud env), -50dB (quiet env)"
echo
read -rp "Value [-40dB]: " silence_threshold
silence_threshold="${silence_threshold:--40dB}"
echo

# ---- step 3: max segment seconds ----
echo "[3/3] Max segment seconds"
echo
echo "  Hard cap on a single recording. Also bounds how long a stale ffmpeg"
echo "  keeps running after USB unplug before the next iteration retries."
echo
read -rp "Value [60]: " max_segment
max_segment="${max_segment:-60}"
if ! [[ "$max_segment" =~ ^[1-9][0-9]*$ ]]; then
    echo "  Invalid integer. Using 60." >&2
    max_segment=60
fi
echo

# ---- summary + confirm ----
echo "Summary:"
if [ -n "$audio_input_device" ]; then
    echo "  audio_input_device = \"$audio_input_device\""
else
    echo "  audio_input_device = (system default)"
fi
echo "  silence_threshold  = \"$silence_threshold\""
echo "  max_segment_sec    = $max_segment"
echo
read -rp "Write to $CONFIG_FILE? [Y/n] " write
case "$write" in
    [Nn]*) echo "Aborted; nothing written."; exit 0 ;;
esac

# ---- write ----
{
    echo "# Daily Work Capture System config"
    printf '# Generated by bin/configure.sh on %s\n' "$(date '+%Y-%m-%d %H:%M:%S')"
    echo
    if [ -n "$audio_input_device" ]; then
        printf 'audio_input_device = "%s"\n' "$audio_input_device"
    else
        echo "# audio_input_device = \"...\""
    fi
    printf 'silence_threshold = "%s"\n' "$silence_threshold"
    printf 'max_segment_sec = %d\n' "$max_segment"
} > "$CONFIG_FILE"

echo
echo "Wrote $CONFIG_FILE"
echo "Re-run this script anytime, or edit the file directly."
